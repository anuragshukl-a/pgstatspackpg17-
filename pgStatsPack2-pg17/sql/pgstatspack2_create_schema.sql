-- pgStatsPack2 for PostgreSQL 17 / 18 (Amazon RDS and Aurora PostgreSQL compatible)
-- Schema, tables, views and configuration.
--
-- Idempotent: safe to re-run. Existing snapshot data is kept.
-- Requires PostgreSQL 16 or later (designed and tested for 17 and 18).

\set ON_ERROR_STOP on
SET client_min_messages TO warning;

DO $$
BEGIN
    IF current_setting('server_version_num')::int < 160000 THEN
        RAISE EXCEPTION 'pgStatsPack2 (pg17 edition) requires PostgreSQL 16 or later; this server is %',
            current_setting('server_version');
    END IF;

    -- Refuse to install on top of the legacy 0.1.0 schema (e.g. after an in-place
    -- RDS major-version upgrade). Its tables have a different layout.
    IF to_regclass('pgstatspack2.pgstatspack2_version') IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM pg_attribute
                       WHERE attrelid = to_regclass('pgstatspack2.pgstatspack2_version')
                         AND attname = 'edition') THEN
        RAISE EXCEPTION 'A legacy pgStatsPack2 schema (0.1.x) exists in database %. '
            'Run sql/pgstatspack2_uninstall.sql first (or install.sh --drop-old).', current_database();
    END IF;
END
$$;

CREATE SCHEMA IF NOT EXISTS pgstatspack2;
SET search_path TO pgstatspack2, pg_catalog;

-- ---------------------------------------------------------------------------
-- Version / configuration
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_version
(
    schema_version  text        NOT NULL,
    edition         text        NOT NULL,
    installed_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pgstatspack2_config
(
    name        text PRIMARY KEY,
    value       text NOT NULL,
    description text
);

INSERT INTO pgstatspack2_config (name, value, description) VALUES
    ('retention',        '30 days', 'Snapshots older than this are removed by pgstatspack2_delete_snap()'),
    ('statements_limit', '1000',    'Max pg_stat_statements rows stored per snapshot (top N by exec+plan time)'),
    ('collect_sizes',    'on',      'Collect table/index sizes (pg_table_size/pg_relation_size). Turn off for databases with very many relations'),
    ('statements_view',  '',        'Optional override for the pg_stat_statements relation (schema.view). Empty = auto-detect')
ON CONFLICT (name) DO NOTHING;

-- ---------------------------------------------------------------------------
-- Name dictionary (keeps per-snapshot rows small)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_names
(
    nameid  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text NOT NULL UNIQUE
);

-- ---------------------------------------------------------------------------
-- Snapshot header
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_snap
(
    snapid             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts                 timestamptz NOT NULL DEFAULT clock_timestamp(),
    description        text,
    server_version_num integer,
    server_version     text,
    is_aurora          boolean,
    postmaster_start   timestamptz,
    pgss_found         boolean,
    db_size            bigint,
    elapsed_ms         numeric
);
CREATE INDEX IF NOT EXISTS pgstatspack2_snap_ts_idx ON pgstatspack2_snap (ts);

-- ---------------------------------------------------------------------------
-- pg_stat_database (all databases in the cluster)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_database
(
    snapid                   bigint  NOT NULL REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    datid                    oid     NOT NULL,
    dbnameid                 integer NOT NULL,
    numbackends              integer,
    xact_commit              bigint,
    xact_rollback            bigint,
    blks_read                bigint,
    blks_hit                 bigint,
    tup_returned             bigint,
    tup_fetched              bigint,
    tup_inserted             bigint,
    tup_updated              bigint,
    tup_deleted              bigint,
    conflicts                bigint,
    temp_files               bigint,
    temp_bytes               bigint,
    deadlocks                bigint,
    checksum_failures        bigint,
    blk_read_time            double precision,
    blk_write_time           double precision,
    session_time             double precision,
    active_time              double precision,
    idle_in_transaction_time double precision,
    sessions                 bigint,
    sessions_abandoned       bigint,
    sessions_fatal           bigint,
    sessions_killed          bigint,
    stats_reset              timestamptz,
    PRIMARY KEY (snapid, datid)
);

-- ---------------------------------------------------------------------------
-- Tables (pg_stat_all_tables + pg_statio_all_tables)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_tables
(
    snapid              bigint  NOT NULL REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    table_name_id       integer NOT NULL,
    relid               oid,
    seq_scan            bigint,
    seq_tup_read        bigint,
    idx_scan            bigint,
    idx_tup_fetch       bigint,
    n_tup_ins           bigint,
    n_tup_upd           bigint,
    n_tup_del           bigint,
    n_tup_hot_upd       bigint,
    n_tup_newpage_upd   bigint,
    n_live_tup          bigint,
    n_dead_tup          bigint,
    n_mod_since_analyze bigint,
    n_ins_since_vacuum  bigint,
    last_seq_scan       timestamptz,
    last_idx_scan       timestamptz,
    last_vacuum         timestamptz,
    last_autovacuum     timestamptz,
    last_analyze        timestamptz,
    last_autoanalyze    timestamptz,
    vacuum_count        bigint,
    autovacuum_count    bigint,
    analyze_count       bigint,
    autoanalyze_count   bigint,
    heap_blks_read      bigint,
    heap_blks_hit       bigint,
    idx_blks_read       bigint,
    idx_blks_hit        bigint,
    toast_blks_read     bigint,
    toast_blks_hit      bigint,
    tidx_blks_read      bigint,
    tidx_blks_hit       bigint,
    tbl_size            bigint,
    idx_size            bigint,
    PRIMARY KEY (snapid, table_name_id)
);

-- ---------------------------------------------------------------------------
-- Indexes (pg_stat_all_indexes + pg_statio_all_indexes)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_indexes
(
    snapid          bigint  NOT NULL REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    index_name_id   integer NOT NULL,
    table_name_id   integer NOT NULL,
    indexrelid      oid,
    relid           oid,
    idx_scan        bigint,
    idx_tup_read    bigint,
    idx_tup_fetch   bigint,
    last_idx_scan   timestamptz,
    idx_blks_read   bigint,
    idx_blks_hit    bigint,
    idx_size        bigint,
    PRIMARY KEY (snapid, index_name_id)
);

-- ---------------------------------------------------------------------------
-- Sequences
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_sequences
(
    snapid           bigint  NOT NULL REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    sequence_name_id integer NOT NULL,
    seq_blks_read    bigint,
    seq_blks_hit     bigint,
    PRIMARY KEY (snapid, sequence_name_id)
);

-- ---------------------------------------------------------------------------
-- Non-default settings
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_settings
(
    snapid      bigint  NOT NULL REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    name_id     integer NOT NULL,
    setting_id  integer NOT NULL,
    source_id   integer NOT NULL,
    unit        text,
    PRIMARY KEY (snapid, name_id)
);

-- ---------------------------------------------------------------------------
-- pg_stat_statements (current database only)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_query_text
(
    queryid     bigint PRIMARY KEY,
    query       text,
    first_seen  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pgstatspack2_statements
(
    snapid              bigint  NOT NULL REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    userid              oid     NOT NULL,
    user_name_id        integer NOT NULL,
    queryid             bigint  NOT NULL,
    toplevel            boolean NOT NULL,
    plans               bigint,
    total_plan_time     double precision,
    calls               bigint,
    total_exec_time     double precision,
    "rows"              bigint,
    shared_blks_hit     bigint,
    shared_blks_read    bigint,
    shared_blks_dirtied bigint,
    shared_blks_written bigint,
    local_blks_hit      bigint,
    local_blks_read     bigint,
    temp_blks_read      bigint,
    temp_blks_written   bigint,
    blk_read_time       double precision,   -- shared_blk_read_time on PG17+
    blk_write_time      double precision,   -- shared_blk_write_time on PG17+
    wal_records         bigint,
    wal_fpi             bigint,
    wal_bytes           numeric,
    stats_since         timestamptz,        -- PG17+, NULL before
    PRIMARY KEY (snapid, userid, queryid, toplevel)
);
CREATE INDEX IF NOT EXISTS pgstatspack2_statements_queryid_idx ON pgstatspack2_statements (queryid);

-- ---------------------------------------------------------------------------
-- User functions (needs track_functions = pl or all)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_functions
(
    snapid           bigint  NOT NULL REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    funcid           oid     NOT NULL,
    function_name_id integer NOT NULL,
    calls            bigint,
    total_time       double precision,
    self_time        double precision,
    PRIMARY KEY (snapid, funcid)
);

-- ---------------------------------------------------------------------------
-- Background writer + checkpointer (merged; PG17 split them into two views)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_bgwriter
(
    snapid                 bigint NOT NULL PRIMARY KEY REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    checkpoints_timed      bigint,   -- pg_stat_checkpointer.num_timed      (PG17+)
    checkpoints_req        bigint,   -- pg_stat_checkpointer.num_requested  (PG17+)
    checkpoints_done       bigint,   -- pg_stat_checkpointer.num_done       (PG18+)
    restartpoints_timed    bigint,
    restartpoints_req      bigint,
    restartpoints_done     bigint,
    checkpoint_write_time  double precision,
    checkpoint_sync_time   double precision,
    buffers_checkpoint     bigint,   -- pg_stat_checkpointer.buffers_written (PG17+)
    slru_written           bigint,   -- PG18+
    buffers_clean          bigint,
    maxwritten_clean       bigint,
    buffers_backend        bigint,   -- derived from pg_stat_io on PG17+
    buffers_backend_fsync  bigint,   -- derived from pg_stat_io on PG17+
    buffers_alloc          bigint
);

-- ---------------------------------------------------------------------------
-- WAL (pg_stat_wal)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_wal
(
    snapid           bigint NOT NULL PRIMARY KEY REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    wal_records      bigint,
    wal_fpi          bigint,
    wal_bytes        numeric,
    wal_buffers_full bigint,
    stats_reset      timestamptz
);

-- ---------------------------------------------------------------------------
-- I/O by backend type / object / context (pg_stat_io)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pgstatspack2_io
(
    snapid         bigint NOT NULL REFERENCES pgstatspack2_snap ON DELETE CASCADE,
    backend_type   text   NOT NULL,
    object         text   NOT NULL,
    context        text   NOT NULL,
    reads          bigint,
    read_bytes     numeric,
    read_time      double precision,
    writes         bigint,
    write_bytes    numeric,
    write_time     double precision,
    writebacks     bigint,
    writeback_time double precision,
    extends        bigint,
    extend_bytes   numeric,
    extend_time    double precision,
    hits           bigint,
    evictions      bigint,
    reuses         bigint,
    fsyncs         bigint,
    fsync_time     double precision,
    PRIMARY KEY (snapid, backend_type, object, context)
);

-- ---------------------------------------------------------------------------
-- Convenience views (names resolved)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW pgstatspack2_database_v AS
    SELECT d.snapid, d.datid, n.name AS datname, d.numbackends, d.xact_commit, d.xact_rollback,
           d.blks_read, d.blks_hit, d.tup_returned, d.tup_fetched, d.tup_inserted, d.tup_updated,
           d.tup_deleted, d.conflicts, d.temp_files, d.temp_bytes, d.deadlocks, d.checksum_failures,
           d.blk_read_time, d.blk_write_time, d.session_time, d.active_time,
           d.idle_in_transaction_time, d.sessions, d.sessions_abandoned, d.sessions_fatal,
           d.sessions_killed, d.stats_reset
    FROM pgstatspack2_database d
    JOIN pgstatspack2_names n ON n.nameid = d.dbnameid;

CREATE OR REPLACE VIEW pgstatspack2_tables_v AS
    SELECT n.name AS table_name, t.*
    FROM pgstatspack2_tables t
    JOIN pgstatspack2_names n ON n.nameid = t.table_name_id;

CREATE OR REPLACE VIEW pgstatspack2_indexes_v AS
    SELECT n1.name AS index_name, n2.name AS table_name, i.*
    FROM pgstatspack2_indexes i
    JOIN pgstatspack2_names n1 ON n1.nameid = i.index_name_id
    JOIN pgstatspack2_names n2 ON n2.nameid = i.table_name_id;

CREATE OR REPLACE VIEW pgstatspack2_sequences_v AS
    SELECT s.snapid, n.name AS sequence_name, s.seq_blks_read, s.seq_blks_hit
    FROM pgstatspack2_sequences s
    JOIN pgstatspack2_names n ON n.nameid = s.sequence_name_id;

CREATE OR REPLACE VIEW pgstatspack2_settings_v AS
    SELECT s.snapid, n1.name AS name, n2.name AS setting, s.unit, n3.name AS source
    FROM pgstatspack2_settings s
    JOIN pgstatspack2_names n1 ON n1.nameid = s.name_id
    JOIN pgstatspack2_names n2 ON n2.nameid = s.setting_id
    JOIN pgstatspack2_names n3 ON n3.nameid = s.source_id;

CREATE OR REPLACE VIEW pgstatspack2_statements_v AS
    SELECT n.name AS user_name, q.query, s.*
    FROM pgstatspack2_statements s
    JOIN pgstatspack2_names n ON n.nameid = s.user_name_id
    LEFT JOIN pgstatspack2_query_text q ON q.queryid = s.queryid;

CREATE OR REPLACE VIEW pgstatspack2_functions_v AS
    SELECT f.snapid, f.funcid, n.name AS function_name, f.calls, f.total_time, f.self_time
    FROM pgstatspack2_functions f
    JOIN pgstatspack2_names n ON n.nameid = f.function_name_id;

-- ---------------------------------------------------------------------------
-- Version stamp
-- ---------------------------------------------------------------------------
DELETE FROM pgstatspack2_version;
INSERT INTO pgstatspack2_version (schema_version, edition) VALUES ('2.0.0', 'pg17');
